import { PGlite } from '@electric-sql/pglite'
import { readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
const db = new PGlite()
await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;`)
await db.exec(await readFile('supabase/migrations/001_game.sql', 'utf8'))
async function call(fn, values = [], role = 'anon') {
  await db.exec(`set role ${role}`)
  try { return (await db.query(`select public.${fn}(${values.map((_,i) => `$${i+1}`).join(',')}) as result`, values)).rows[0].result }
  finally { await db.exec('reset role') }
}
const token = randomUUID()
let game = await call('start_game', ['נועה', token])
assert.equal(game.solved, 0)
assert.equal(game.player_name, 'נועה')
assert.deepEqual((await call('start_game', ['Different name', token])).question, game.question)
assert.equal((await call('start_game', ['Different name', token])).player_name, 'נועה')
await assert.rejects(call('start_game', [' ', randomUUID()]))
await assert.rejects(call('get_game', [randomUUID()]), /SESSION_NOT_FOUND/)
const originalQuestion = game.question
const wrong = await call('answer_question', [token, originalQuestion.id, 999])
assert.equal(wrong.correct, false)
assert.equal(wrong.solved, 0)
assert.deepEqual(wrong.question, originalQuestion)
await assert.rejects(call('answer_question', [token, (originalQuestion.id + 1) % 100, 1]), /QUESTION_MISMATCH/)
const seen = new Set()
for (let i = 0; i < 100; i++) {
  const q = game.question
  assert.ok(q && !seen.has(q.id))
  seen.add(q.id)
  const product = q.a * q.b
  game = await call('answer_question', [token, q.id, product])
  assert.equal(game.solved, i + 1)
  assert.equal(game.correct, true)
  const retried = await call('answer_question', [token, q.id, product])
  assert.equal(retried.solved, i + 1)
  assert.deepEqual(retried.question, game.question)
}
assert.equal(game.finished, true)
assert.equal(game.question, null)
assert.equal(seen.size, 100)
const finished = await call('finish_game', [token])
assert.equal(finished.elapsed_ms, game.elapsed_ms)
const token2 = randomUUID()
let partial = await call('start_game', ['נועה', token2])
partial = await call('answer_question', [token2, partial.question.id, partial.question.a * partial.question.b])
partial = await call('finish_game', [token2])
assert.equal(partial.solved, 1)
assert.equal(partial.finished, true)
assert.equal((await call('answer_question', [token2, 999, 999])).solved, 1)
const token3 = randomUUID()
await call('start_game', ['Zero', token3])
await call('finish_game', [token3])
let scores = await call('get_leaderboard', [0])
assert.equal(scores.length, 3)
assert.deepEqual(scores.map(s => s.solved), [100, 1, 0])
assert.ok(!('token' in scores[0]) && !('deck' in scores[0]))
assert.equal(scores.filter(s => s.player_name === 'נועה').length, 2)
assert.deepEqual(await call('get_leaderboard', [3]), [])
// Same score is ordered by server duration, even if the quicker attempt was created later.
await db.query('update game_private.games set solved = 1, elapsed_ms = 5 where token = $1', [token3])
await db.query('update game_private.games set elapsed_ms = 10 where token = $1', [token2])
scores = await call('get_leaderboard', [0])
assert.deepEqual(scores.map(s => s.player_name), ['נועה', 'Zero', 'נועה'])
// Anonymous clients cannot read private rows or write invented final scores.
await db.exec('set role anon')
await assert.rejects(db.query('select * from game_private.games'), /permission denied/)
await assert.rejects(db.query('update game_private.games set solved = 100'), /permission denied/)
await db.exec('reset role')
assert.equal(await call('is_game_admin'), false)
await assert.rejects(call('delete_attempt', [scores[0].id]), /permission denied/)
await assert.rejects(call('reset_competition', [], 'authenticated'), /ADMIN_REQUIRED/)
const adminId = randomUUID()
await db.query('insert into auth.users values ($1)', [adminId])
await db.query('insert into game_private.admins values ($1)', [adminId])
await db.query("select set_config('request.jwt.claim.sub', $1, false)", [adminId])
assert.equal(await call('is_game_admin', [], 'authenticated'), true)
await call('delete_attempt', [scores[0].id], 'authenticated')
assert.equal((await call('get_leaderboard')).length, 2)
const activeToken = randomUUID()
await call('start_game', ['Active', activeToken])
await call('reset_competition', [], 'authenticated')
assert.deepEqual(await call('get_leaderboard'), [])
await assert.rejects(call('get_game', [activeToken]), /SESSION_NOT_FOUND/)
await db.close()
console.log('Database integration passed: 100 questions, retry idempotency, ranking, partial/zero scores, private tables, admin authorization, deletion and reset.')
